-- Справочник аэропортов для расчёта авиадоставки.
--
-- Авиаплечо считается не от склада до склада, а от аэропорта до аэропорта:
-- до аэропорта вылета товар везут по земле, из аэропорта прилёта партнёр забирает сам.
--
-- Координаты приблизительные (точность порядка километра) и внесены вручную.
-- Для боевого использования справочник стоит перезалить из открытого набора
-- OurAirports (public domain), отфильтровав грузовые аэропорты.

create table airports
(
    id        bigint        not null generated by default as identity,
    iata      varchar(3)    not null,
    name      varchar(255)  not null,
    city      varchar(255),
    latitude  numeric(9, 6) not null,
    longitude numeric(9, 6) not null,
    primary key (id),
    constraint uq_airports_iata unique (iata)
);

