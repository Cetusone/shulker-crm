create table partners
(
    id            bigint       not null generated by default as identity,
    name          varchar(255) not null,
    api_key       varchar(100) not null unique,
    contact_email varchar(255),
    is_active     boolean      not null,
    is_deleted    boolean      not null,
    created_at    timestamp(6) not null,
    updated_at    timestamp(6) not null,
    primary key (id)
);

create table products
(
    id          bigint         not null generated by default as identity,
    name        varchar(255)   not null,
    sku         varchar(50)    not null unique,
    description TEXT,
    weight_kg   numeric(10, 4) not null,
    volume_m3   numeric(10, 6) not null,
    is_deleted  boolean        not null,
    created_at  timestamp(6)   not null,
    updated_at  timestamp(6)   not null,
    primary key (id)
);

create table transports
(
    id             bigint                   not null generated by default as identity,
    name           varchar(255)             not null,
    transport_type varchar(20)              not null check (transport_type in ('AUTO', 'RAILWAY', 'AVIATION')),
    max_weight_kg  numeric(10, 2)           not null,
    max_volume_m3  numeric(10, 2)           not null,
    speed_km_h     numeric(8, 2)            not null,
    cost_per_km    numeric(10, 2)           not null,
    is_deleted     boolean                  not null,
    created_at     timestamp(6) with time zone not null,
    updated_at     timestamp(6) with time zone not null,
    primary key (id)
);

create table own_warehouses
(
    id         bigint                      not null generated by default as identity,
    name       varchar(255)                not null,
    address    TEXT,
    latitude   numeric(9, 6)               not null,
    longitude  numeric(9, 6)               not null,
    is_active  boolean                     not null,
    is_deleted boolean                     not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id)
);

-- ---------------------------------------------------------------- зависимые сущности

create table partner_warehouses
(
    id           bigint        not null generated by default as identity,
    partner_id   bigint        not null,
    name         varchar(255)  not null,
    address      TEXT,
    latitude     numeric(9, 6) not null,
    longitude    numeric(9, 6) not null,
    accepts_land boolean       not null,
    accepts_sea  boolean       not null,
    accepts_air  boolean       not null,
    is_active    boolean       not null,
    is_deleted   boolean       not null,
    created_at   timestamp(6)  not null,
    updated_at   timestamp(6)  not null,
    primary key (id)
);

create table product_characteristics
(
    id              bigint       not null generated by default as identity,
    product_id      bigint       not null,
    attribute_name  varchar(100) not null,
    attribute_value varchar(500) not null,
    is_deleted      boolean      not null,
    primary key (id),
    constraint uq_product_characteristic_name unique (product_id, attribute_name)
);

create table own_warehouse_transports
(
    id               bigint  not null generated by default as identity,
    own_warehouse_id bigint  not null,
    transport_id     bigint  not null,
    is_deleted       boolean not null,
    primary key (id),
    constraint uk_warehouse_transport unique (own_warehouse_id, transport_id)
);

create table stocks
(
    id               bigint       not null generated by default as identity,
    own_warehouse_id bigint       not null,
    product_id       bigint       not null,
    quantity         integer      not null,
    reserved_quantity integer     not null,
    version          bigint       not null,
    is_deleted       boolean      not null,
    updated_at       timestamp(6) not null,
    primary key (id),
    constraint uq_stocks_warehouse_product unique (own_warehouse_id, product_id)
);

create table stock_movements
(
    id              bigint       not null generated by default as identity,
    stock_id        bigint       not null,
    movement_type   varchar(20)  not null check (movement_type in ('REPLENISHMENT', 'SHIPMENT', 'ADJUSTMENT')),
    quantity_change integer      not null,
    quantity_after  integer      not null,
    reason          TEXT,
    is_deleted      boolean      not null,
    created_at      timestamp(6) not null,
    primary key (id)
);

alter table partner_warehouses
    add constraint fk_partner_warehouses_partner
        foreign key (partner_id) references partners;

alter table product_characteristics
    add constraint fk_product_characteristics_product
        foreign key (product_id) references products on delete cascade;

alter table own_warehouse_transports
    add constraint fk_own_warehouse_transports_warehouse
        foreign key (own_warehouse_id) references own_warehouses;

alter table own_warehouse_transports
    add constraint fk_own_warehouse_transports_transport
        foreign key (transport_id) references transports;

alter table stocks
    add constraint fk_stocks_product
        foreign key (product_id) references products;

alter table stock_movements
    add constraint fk_stock_movements_stock
        foreign key (stock_id) references stocks;

create index idx_partners_is_active on partners (is_active);

create index idx_products_name on products (name);

create index idx_transports_transport_type on transports (transport_type);

create index idx_warehouses_partner_id on partner_warehouses (partner_id);
create index idx_warehouses_is_active on partner_warehouses (is_active);

create index idx_product_characteristics_product_id on product_characteristics (product_id);

create index idx_own_warehouse_transports_transport_id on own_warehouse_transports (transport_id);

create index idx_stocks_own_warehouse_id on stocks (own_warehouse_id);
create index idx_stocks_product_id on stocks (product_id);

create index idx_stock_movements_stock_id on stock_movements (stock_id);
create index idx_stock_movements_created_at on stock_movements (created_at);
create index idx_stock_movements_type on stock_movements (movement_type);
